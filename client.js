    function RefineToolbar(props) {
      const { inputActions, useInput, sessionId } = props
      // Re-render when the host switches language so the copy follows immediately.
      useLocaleRevision(props)
      const t = typeof props.translate === 'function' ? props.translate : typeof props.t === 'function' ? props.t : (key) => key
      const draft = useInput((state) => state.draft)
      const phase = useInput((state) => state.phase)
      // Reference chips (@file / session) cannot survive a plain-text rewrite;
      // optimizing such a draft would silently drop them.
      const hasReferences = useInput((state) => Array.isArray(state.occurrences) && state.occurrences.length > 0)
      const preferences = useSharedSettings()
      const [busy, setBusy] = React.useState(false)
      const [original, setOriginal] = React.useState(null)
      const [refined, setRefined] = React.useState(null)
      const [message, setMessage] = React.useState(null)
      const draftRef = React.useRef(draft)
      draftRef.current = draft
      const mounted = React.useRef(true)
      const inflight = React.useRef(null)
      /**
       * Owner of the empty-draft hint animation (type -> hold -> erase).
       *
       * `timer` is the only pending step; `phase` records the current stage; `chars`
       * is the full hint text. All of it is plain mutable state because the run loop
       * fires every few dozen milliseconds and must not re-render the composer.
       * `run` is compared by identity so a cancelled run cannot be revived by a
       * timer that was already queued when the cancellation happened.
       */
      const hintRun = React.useRef({ timer: null, phase: 'idle', chars: [], index: 0 })

      const abortInflight = () => {
        const controller = inflight.current
        inflight.current = null
        if (controller) controller.abort()
      }

      /**
       * Stop the hint animation. By default it also clears any half-typed text the
       * animation itself produced, but leaves text the user typed in the meantime.
       */
      const cancelHintAnimation = (options) => {
        const run = hintRun.current
        if (run.timer !== null) {
          clearTimeout(run.timer)
          run.timer = null
        }
        const wasAnimating = run.phase !== 'idle'
        const owned = run.chars.slice(0, run.index).join('')
        run.phase = 'idle'
        run.chars = []
        run.index = 0
        if (wasAnimating && !options?.keepText && mounted.current) {
          const current = draftRef.current
          if (owned && current === owned) inputActions.setDraft('')
        }
      }

      /**
       * Type a hint into the composer, hold it, then erase it character by
       * character.
       *
       * The text goes through `inputActions.setDraft`, never the DOM, so the host's
       * own persistence and undo see ordinary edits. Characters are written and
       * removed a few at a time: one `setDraft` per character would make a long
       * localized hint crawl, and a single write would look pasted rather than
       * typed. Timing is deliberately unhurried on the way out — the erase is the
       * part the eye follows — while typing stays brisk enough to feel responsive.
       */
      const startHintAnimation = (text) => {
        cancelHintAnimation({ keepText: true })
        const run = { timer: null, phase: 'typing', chars: [...text], index: 0 }
        hintRun.current = run

        // The hint is typed into the composer, so an empty string has nothing to
        // show; the button simply does nothing rather than falling back to a bubble.
        if (!run.chars.length) {
          run.phase = 'idle'
          return
        }

        const step = () => {
          if (!mounted.current || hintRun.current !== run) return
          if (run.phase === 'typing') {
            run.index = Math.min(run.chars.length, run.index + HINT_CHUNK)
            inputActions.setDraft(run.chars.slice(0, run.index).join(''))
            if (run.index >= run.chars.length) {
              // Fully typed: hold so the hint can actually be read.
              run.phase = 'holding'
              run.timer = setTimeout(() => {
                if (!mounted.current || hintRun.current !== run) return
                run.phase = 'erasing'
                step()
              }, HINT_HOLD_MS)
            } else {
              run.timer = setTimeout(step, HINT_TYPE_MS)
            }
            return
          }
          if (run.phase === 'erasing') {
            run.index = Math.max(0, run.index - HINT_ERASE_CHUNK)
            inputActions.setDraft(run.chars.slice(0, run.index).join(''))
            if (run.index <= 0) {
              run.phase = 'idle'
              run.timer = null
              run.chars = []
              // Animation done: the composer is empty again and no bubble is shown.
              // The hint lives in the draft, so nothing further is needed here.
            } else {
              run.timer = setTimeout(step, HINT_ERASE_MS)
            }
          }
        }

        run.timer = setTimeout(step, HINT_TYPE_MS)
      }

      React.useEffect(() => {
        mounted.current = true
        loadSharedSettings()
        return () => {
          mounted.current = false
          abortInflight()
          const run = hintRun.current
          if (run.timer !== null) clearTimeout(run.timer)
          run.timer = null
          run.phase = 'idle'
        }
      }, [])

      React.useEffect(() => {
        abortInflight()
        cancelHintAnimation()
        setBusy(false)
        setOriginal(null)
        setRefined(null)
        setMessage(null)
      }, [sessionId])

      React.useEffect(() => {
        if (refined === null) return
        if (draft === refined) return
        // Sending or clearing the optimized draft ends the undo window.
        if (draft.trim() === '') {
          setRefined(null)
          setOriginal(null)
          setMessage(null)
        }
      }, [draft, refined])

      // Typing while the hint is playing cancels it at once. The animation is
      // guidance; the moment the user starts writing for real it must stop rather
      // than keep overwriting their text. The comparison against the exact prefix
      // the animation owns is what keeps our own per-tick writes from cancelling it.
      React.useEffect(() => {
        const run = hintRun.current
        if (run.phase === 'idle') return
        const owned = run.chars.slice(0, run.index).join('')
        if (draft === owned) return
        cancelHintAnimation()
      }, [draft])

      React.useEffect(() => {
        if (message === null) return
        const timer = setTimeout(() => setMessage(null), message.level === 'error' ? 9000 : 4000)
        return () => clearTimeout(timer)
      }, [message])

      const optimize = async () => {
        if (busy) return
        if (hasReferences) {
          setMessage({ level: 'error', text: t('tool.references') })
          return
        }
        const source = draft
        if (!source.trim()) {
          // Empty draft: play the hint inside the composer instead of only a bubble.
          startHintAnimation(t('tool.hintType'))
          return
        }
        abortInflight()
        const controller = new AbortController()
        inflight.current = controller
        setBusy(true)
        setMessage(null)
        // The streamed text is written into the composer as it arrives. The
        // original draft is remembered first so the control can offer "undo"
        // even while the stream is still running.
        setOriginal(source)
        try {
          // The stream writes the refined prompt straight into the draft. The
          // user can watch it being written, which turns a long wait into
          // something readable.
          let streamed = ''
          // Once the user edits the draft themselves, the stream stops writing:
          // their text must not be overwritten by the next delta.
          let userTookOver = false
          const result = await streamRequest(
            '/optimize/stream',
            { text: source, sessionId },
            async (piece) => {
              if (!mounted.current) return
              if (userTookOver) return
              // The draft holds either the original text or what the stream has
              // written so far. Anything else means the user typed.
              if (draftRef.current !== source && draftRef.current !== streamed) {
                userTookOver = true
                return
              }
              streamed += piece
              // The Host sends the raw model output while it streams; the
              // final `done` event carries the cleaned version.
              inputActions.setDraft(streamed)
            },
            controller.signal,
          )
          const optimized = typeof result.optimized === 'string' ? result.optimized.trim() : ''
          if (!optimized) throw new Error(t('tool.empty'))
          if (!mounted.current) return
          if (userTookOver) {
            // The user typed while the model was writing; their text wins and the
            // result is not applied.
            setMessage({ level: 'info', text: t('tool.draftChanged') })
            setOriginal(null)
            return
          }
          setRefined(optimized)
          inputActions.setDraft(optimized)
        } catch (error) {
          // A cancelled or superseded request is not a failure worth a message.
          if (isAbortError(error) || !mounted.current) return
          // The partial stream may have replaced the draft; restore the original
          // so a failed optimization never leaves half a prompt behind.
          if (draftRef.current !== source) inputActions.setDraft(source)
          setOriginal(null)
          setMessage({ level: 'error', text: t('tool.failed', { message: errorMessage(error) }) })
        } finally {
          if (inflight.current === controller) inflight.current = null
          if (mounted.current) setBusy(false)
        }
      }

      const undo = () => {
        abortInflight()
        cancelHintAnimation()
        if (original === null) return
        inputActions.setDraft(original)
        setOriginal(null)
        setRefined(null)
        setMessage(null)
      }

      const locked = phase !== 'plain'
      const isRefined = refined !== null && original !== null
      // Undo stays available even while the composer is busy, so a mistaken
      // optimization can always be reverted.
      const disabled = isRefined ? false : busy || locked || hasReferences
      // The preference drives both states: when it is off the control shows an
      // icon only, in the optimized state too, so it never changes width.
      const showText = preferences.showLabel === true
      const title = isRefined ? t('tool.undoHint') : hasReferences ? t('tool.referencesHint') : t('tool.optimizeHint')
      const label = busy ? t('tool.busy') : isRefined ? t('tool.undo') : t('tool.optimize')

      return h(
        'div',
        { className: 'dsh-pr-wrap' },
        h('style', null, toolbarCss),
        message ? h('div', { className: 'dsh-pr-tip', 'data-level': message.level, role: message.level === 'error' ? 'alert' : 'status' }, message.text) : null,
        h(
          'button',
          {
            type: 'button',
            className: 'dsh-pr-tool',
            'data-icon-only': showText ? 'false' : 'true',
            'data-refined': isRefined ? 'true' : 'false',
            'data-refs': hasReferences && !isRefined ? 'true' : 'false',
            disabled,
            title,
            'aria-label': label,
            'aria-busy': busy ? 'true' : 'false',
            // Keep the caret/selection in the draft editor, like the host toolbar controls.
            onMouseDown: (event) => event.preventDefault(),
            onClick: isRefined ? undo : optimize,
          },
          busy ? h(Spinner) : isRefined ? h(IconUndo) : h(IconSparkle),
          showText ? h('span', null, label) : null,
        ),
      )
    }

