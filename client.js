    function apiUrl(path) {
      const origin = typeof location !== 'undefined' && location.origin && location.origin !== 'null' ? location.origin : ''
      return origin + ROUTE + path
    }

    /** Host-issued request ticket; /status is the only route that serves it. */
    let ticketPromise = null

    function fetchTicket(force) {
      if (!force && ticketPromise) return ticketPromise
      ticketPromise = fetch(apiUrl('/status'), {
        credentials: 'same-origin',
        headers: { 'x-dsh-prompt-optimization': '1' },
      })
        .then((response) => (response.ok ? response.json() : null))
        .then((payload) => (payload && typeof payload.ticket === 'string' ? payload.ticket : null))
        .catch(() => null)
      return ticketPromise
    }

    class RequestError extends Error {
      constructor(message, status, code) {
        super(message)
        this.status = status
        this.code = code
      }
    }

    function isAbortError(error) {
      return Boolean(error && (error.name === 'AbortError' || error.code === 'aborted' || error.status === 499))
    }

    /**
     * One plugin request. Retries once after refreshing the ticket when the Host
     * rejected a stale one (page kept open across a Host restart).
     */
    async function request(path, options) {
      const init = options || {}
      const send = (ticket) =>
        fetch(apiUrl(path), {
          credentials: 'same-origin',
          ...init,
          headers: {
            'content-type': 'application/json',
            'x-dsh-prompt-optimization': '1',
            ...(ticket ? { 'x-dsh-prompt-optimization-ticket': ticket } : {}),
            ...(init.headers || {}),
          },
        })

      let ticket = path === '/status' ? undefined : await fetchTicket(false)
      let response = await send(ticket)
      if (response.status === 403 && path !== '/status') {
        ticket = await fetchTicket(true)
        if (ticket) response = await send(ticket)
      }
      let payload = null
      try {
        payload = await response.json()
      } catch {
        payload = null
      }
      if (!response.ok) {
        const code = payload && payload.error && payload.error.code ? payload.error.code : undefined
        const message = payload && payload.error && payload.error.message ? payload.error.message : `HTTP ${response.status}`
        throw new RequestError(message, response.status, code)
      }
      return payload
    }

    function postJson(path, body, signal) {
      return request(path, { method: 'POST', body: JSON.stringify(body || {}), signal })
    }

    /**
     * One streaming plugin request.
     *
     * The Host answers with newline-delimited JSON: `delta` events carry pieces
     * of the refined prompt, a final `done` event carries the cleaned text.
     * `onDelta` is called for every piece so the composer can fill in while the
     * model is still writing.
     *
     * A ticket rejection is retried the same way as for a plain request, but a
     * retry can only happen before the first byte: once the stream has started
     * the response cannot be replayed.
     */
    async function streamRequest(path, body, onDelta, signal) {
      const init = { method: 'POST', body: JSON.stringify(body || {}), signal }
      const send = (ticket) =>
        fetch(apiUrl(path), {
          credentials: 'same-origin',
          ...init,
          headers: {
            'content-type': 'application/json',
            'x-dsh-prompt-optimization': '1',
            ...(ticket ? { 'x-dsh-prompt-optimization-ticket': ticket } : {}),
            ...(init.headers || {}),
          },
        })

      let ticket = await fetchTicket(false)
      let response = await send(ticket)
      if (response.status === 403) {
        ticket = await fetchTicket(true)
        if (ticket) response = await send(ticket)
      }
      if (!response.ok) {
        let message = `HTTP ${response.status}`
        try {
          const payload = await response.json()
          if (payload?.error?.message) message = payload.error.message
        } catch {
          // A non-JSON error body keeps the status-based message.
        }
        throw new RequestError(message, response.status)
      }
      if (!response.body) {
        // No streaming body (very old browser): fall back to the plain route.
        const payload = await postJson(path.replace(/\/stream$/, ''), body, signal)
        if (typeof payload?.optimized === 'string') await onDelta(payload.optimized)
        return payload
      }

      const reader = response.body.getReader()
      const decoder = new TextDecoder()
      let buffer = ''
      let result = null
      let streamError = ''
      try {
        for (;;) {
          const { value, done } = await reader.read()
          if (done) break
          buffer += decoder.decode(value, { stream: true })
          let boundary = buffer.indexOf('\n')
          while (boundary !== -1) {
            const line = buffer.slice(0, boundary).trim()
            buffer = buffer.slice(boundary + 1)
            if (!line) continue
            let event
            try {
              event = JSON.parse(line)
            } catch {
              continue
            }
            if (event?.type === 'delta' && typeof event.text === 'string') {
              await onDelta(event.text)
            } else if (event?.type === 'done') {
              result = event
            } else if (event?.type === 'error') {
              streamError = event.message || '模型调用失败。'
            }
          }
        }
      } catch (error) {
        if (isAbortError(error)) throw error
        throw new RequestError(errorMessage(error), 0)
      } finally {
        try {
          reader.releaseLock()
        } catch {
          // The reader may already be released after an error.
        }
      }
      if (streamError) throw new RequestError(streamError, 502)
      if (!result) throw new RequestError('模型没有返回结果。', 502)
      return result
    }

    function errorMessage(error) {
      return error instanceof Error ? error.message : String(error)
    }

