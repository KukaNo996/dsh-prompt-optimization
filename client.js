    /** Canonical dictionary key for an active locale id, or undefined when unsupported. */
    function resolveLocale(activeLocale) {
      if (LOCALES[activeLocale]) return activeLocale
      const tag = String(activeLocale || "").toLowerCase().replace(/_/g, "-")
      if (!tag) return undefined
      if (LOCALES[tag]) return tag
      // Primary subtag, then script/region hints for Chinese.
      const primary = tag.split("-")[0]
      if (primary === "zh") {
        if (tag.includes("hant") || tag.includes("tw") || tag.includes("hk") || tag.includes("mo")) return "zh-TW"
        return "zh"
      }
      if (LOCALES[primary]) return primary
      return undefined
    }

    /** Pick the dictionary for the active locale, falling back to English. */
    function dictionaryFor(activeLocale) {
      return LOCALES[resolveLocale(activeLocale)] || LOCALES.en
    }
